// Verbatim migration of the legacy blog.kaiteki.my archive into /blog.
//
//   node scripts/blog-migrate-legacy.mjs            # every post
//   node scripts/blog-migrate-legacy.mjs <slug> ...  # just these legacy slugs
//
// Unlike scripts/blog-import.mjs (which drafts a post for an editorial rewrite),
// this copies each post AS PUBLISHED: same words, same slug, same <title> and
// meta description, same author, same dates, same cover and in-body images.
// The only things dropped are WordPress chrome the new template renders itself
// (the Elementor table of contents, the "BOOK FREE CONSULTATION" button, share
// buttons, spacers, dividers).
//
// Output:
//   content/blog/<slug>.mdx                  body
//   content/blog/media/<slug>/*              cover + in-body images (synced to R2 on deploy)
//   content/data/blog-legacy.ts              Post metadata, merged into content/data/blog.ts
//   scripts/blog-legacy-media.json           old wp-content URL → new CDN URL (feeds the 301 map)
//
// Posts carry `legacy: true`, which exempts them from the house-style half of
// `pnpm check:blog` (em-dashes, meta lengths, lead answer). They were published
// copy on the old host and are moved, not re-edited. Re-running is safe: images
// already on disk are not downloaded again.
