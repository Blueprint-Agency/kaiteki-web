/** Download `url` into content/blog/media/<slug>/, returning its CDN URL. */
async function localise(url, slug, used) {
  const abs = new URL(url, HOST).href.replace(/^http:/, "https:");
  if (mediaMap[abs]?.startsWith(`${CDN}/${slug}/`)) {
    used.add(path.basename(mediaMap[abs]));
    return mediaMap[abs];
  }
  let name = decodeURIComponent(path.basename(new URL(abs).pathname))
    .toLowerCase()
    .replace(/[^a-z0-9._-]+/g, "-");
  const ext = path.extname(name);
  const stem = name.slice(0, name.length - ext.length);
  for (let i = 2; used.has(name); i += 1) name = `${stem}-${i}${ext}`;
  used.add(name);
  const dir = path.join(OUT_IMG, slug);
  await mkdir(dir, { recursive: true });
  const file = path.join(dir, name);
  if (!existsSync(file)) await writeFile(file, Buffer.from(await (await fetchOk(abs)).arrayBuffer()));
  const cdn = `${CDN}/${slug}/${name}`;
  mediaMap[abs] = cdn;
  return cdn;
}

/** [width, height] of a PNG/JPEG/WebP/GIF from its header, or null. */
async function imageSize(file) {
  const b = await readFile(file);
  if (b[0] === 0x89 && b[1] === 0x50) return [b.readUInt32BE(16), b.readUInt32BE(20)];
  if (b.toString("ascii", 0, 3) === "GIF") return [b.readUInt16LE(6), b.readUInt16LE(8)];
  if (b.toString("ascii", 0, 4) === "RIFF" && b.toString("ascii", 8, 12) === "WEBP") {
    const kind = b.toString("ascii", 12, 16);
    if (kind === "VP8X") return [1 + b.readUIntLE(24, 3), 1 + b.readUIntLE(27, 3)];
    if (kind === "VP8 ") return [b.readUInt16LE(26) & 0x3fff, b.readUInt16LE(28) & 0x3fff];
    if (kind === "VP8L") {
      const n = b.readUInt32LE(21);
      return [1 + (n & 0x3fff), 1 + ((n >> 14) & 0x3fff)];
    }
  }
  if (b[0] === 0xff && b[1] === 0xd8) {
    let o = 2;
    while (o + 9 < b.length) {
      if (b[o] !== 0xff) return null;
      const marker = b[o + 1];
      if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker))
        return [b.readUInt16BE(o + 7), b.readUInt16BE(o + 5)];
      o += 2 + b.readUInt16BE(o + 2);
    }
  }
  return null;
}

// ── HTML → MDX ──────────────────────────────────────────────────────────────

const turndown = new TurndownService({
  headingStyle: "atx",
  codeBlockStyle: "fenced",
  bulletListMarker: "-",
  emDelimiter: "*",
  strongDelimiter: "**",
});
turndown.use(gfm);
// Placeholders survive conversion as their own paragraph and become JSX afterwards.
turndown.addRule("block", {
  filter: (n) => n.nodeName === "P" && /^@@BLOCK\d+@@$/.test(n.textContent.trim()),
  replacement: (_c, n) => `\n\n${n.textContent.trim()}\n\n`,
});

/** Characters MDX would read as JSX or an expression, escaped in prose. */
const escapeMdx = (md) =>
  md
    .split("\n")
    .map((line) => (/^@@BLOCK\d+@@$/.test(line.trim()) ? line : line.replace(/[{}<]/g, (c) => `\\${c}`)))
    .join("\n");

async function convert(post, title) {
  const slug = post.slug;
  const doc = domino.createDocument(`<!doctype html><html><body>${post.content.rendered}</body></html>`);
  const body = doc.body;
  const blocks = [];
  const used = new Set();
  const report = { images: 0, videos: 0, toggles: 0, buttonsKept: 0, problems: [] };

  const placeholder = (jsx) => {
    const p = doc.createElement("p");
    p.textContent = `@@BLOCK${blocks.length}@@`;
    blocks.push(jsx);
    return p;
  };
  const widgets = (type) => qsa(body, `[data-widget_type="${type}"]`);

  // Chrome the new template renders itself, or that carries no content.
  for (const sel of [
    "script",
    "style",
    "noscript",
    '[data-widget_type="table-of-contents.default"]',
    '[data-widget_type="share-buttons.default"]',
    '[data-widget_type="spacer.default"]',
    '[data-widget_type="divider.default"]',
    ".elementor-author-box",
  ])
    for (const el of qsa(body, sel)) el.remove();

  // Buttons: the WhatsApp booking CTA is replaced by the page's own CTA. Any
  // other button links to a page, which is content, so it stays as a link.
  for (const w of widgets("button.default")) {
    const a = w.querySelector("a");
    const href = a?.getAttribute("href") || "";
    if (!a || !href || /api\.whatsapp\.com|wa\.me/.test(href)) {
      w.remove();
      continue;
    }
    const p = doc.createElement("p");
    const link = doc.createElement("a");
    link.setAttribute("href", href);
    link.textContent = a.textContent.trim();
    p.appendChild(link);
    w.replaceWith(p);
    report.buttonsKept += 1;
  }

  // YouTube embeds live in the widget's data-settings, not its markup.
  for (const w of widgets("video.default")) {
    const url = JSON.parse(w.getAttribute("data-settings") || "{}").youtube_url || "";
    const id = /(?:youtu\.be\/|shorts\/|embed\/|[?&]v=)([A-Za-z0-9_-]{11})/.exec(url)?.[1];
    if (!id) {
      report.problems.push(`video with no YouTube id: ${url || "(none)"}`);
      w.remove();
      continue;
    }
    w.replaceWith(placeholder(`<YouTube id="${id}" title=${attr(title)} />`));
    report.videos += 1;
  }

  // Toggles (accordions): each item's title in bold, then its content, in place.
  for (const w of widgets("toggle.default")) {
    const frag = doc.createElement("div");
    for (const item of qsa(w, ".elementor-toggle-item")) {
      const t = item.querySelector(".elementor-tab-title")?.textContent.trim();
      const content = item.querySelector(".elementor-tab-content");
      if (t) {
        const p = doc.createElement("p");
        const s = doc.createElement("strong");
        s.textContent = t;
        p.appendChild(s);
        frag.appendChild(p);
      }
      if (content) frag.appendChild(content);
    }
    w.replaceWith(frag);
    report.toggles += 1;
  }

  // Images → <Figure>, downloaded and served from R2.
  for (const img of qsa(body, "img")) {
    const src = img.getAttribute("src");
    if (!src || src.startsWith("data:")) {
      img.remove();
      continue;
    }
    let cdn;
    try {
      cdn = await localise(src, slug, used);
    } catch (e) {
      report.problems.push(`image failed: ${src} (${e.message})`);
      img.remove();
      continue;
    }
    const size = await imageSize(path.join(OUT_IMG, slug, path.basename(cdn)));
    const w = size?.[0] || Number(img.getAttribute("width")) || 4;
    const h = size?.[1] || Number(img.getAttribute("height")) || 3;
    const container = img.closest("figure, .elementor-widget-image, .wp-caption");
    const caption =
      container?.querySelector("figcaption, .widget-image-caption, .wp-caption-text")?.textContent.trim() ?? "";
    const jsx =
      `<Figure src="${cdn}" alt=${attr(img.getAttribute("alt") || "")}` +
      `${caption ? ` caption=${attr(caption)}` : ""} ratio="${w}/${h}" />`;
    if (container) {
      container.replaceWith(placeholder(jsx));
    } else {
      // Inline in a paragraph or list item: the figure goes right after it.
      const host = img.closest("p, li, td, h2, h3, h4, h5, h6");
      const node = img.closest("a") || img;
      if (host && host.textContent.trim()) {
        host.after(placeholder(jsx));
        node.remove();
      } else (host || node).replaceWith(placeholder(jsx));
    }
    report.images += 1;
  }

  // Links: re-point the old host; leave everything else as published.
  for (const a of qsa(body, "a")) {
    const href = a.getAttribute("href") || "";
    const next = rewriteLegacyHref(href);
    if (next) a.setAttribute("href", next);
    else if (legacyPathOf(href)) report.problems.push(`link left on old host: ${href}`);
    else {
      // Old main-site URLs: now the same site, so link straight to the page
      // next.config.ts would 301 them to, instead of through the redirect.
      const main = /^https?:\/\/(?:www\.)?kaiteki\.my(\/[^?#]*)?/i.exec(href);
      if (main) a.setAttribute("href", MAIN_SITE[main[1] || "/"] ?? href.replace(/^http:/, "https:"));
    }
  }

  // Tables: GFM needs a header row and single-line cells, or turndown leaves the
  // table as raw HTML. The legacy tables put labels in a plain first row and
  // wrap cell text in <p>, so promote that row and unwrap the paragraphs.
  for (const table of qsa(body, "table")) {
    for (const p of qsa(table, "td p, th p")) {
      p.after(doc.createTextNode(" "));
      p.replaceWith(...Array.from(p.childNodes));
    }
    if (!qsa(table, "th").length) {
      const first = table.querySelector("tr");
      for (const td of qsa(first, "td")) {
        const th = doc.createElement("th");
        while (td.firstChild) th.appendChild(td.firstChild);
        td.replaceWith(th);
      }
    }
  }

  // One H1 per page and it is the title, so body H1s become H2s. Bold inside a
  // heading is presentational there: unwrapped, the words stay.
  for (const h of qsa(body, "h1")) {
    const h2 = doc.createElement("h2");
    while (h.firstChild) h2.appendChild(h.firstChild);
    h.replaceWith(h2);
  }
  const inHeading = ["h2", "h3", "h4", "h5", "h6"]
    .flatMap((h) => ["strong", "b", "em", "i", "span"].map((t) => `${h} ${t}`))
    .join(", ");
  for (const el of qsa(body, inHeading)) el.replaceWith(...Array.from(el.childNodes));

  // Drop every attribute markdown does not keep, so nothing like style="..."
  // can reach MDX (where it is invalid JSX).
  for (const el of qsa(body, "*")) {
    for (const { name } of Array.from(el.attributes)) {
      const keep =
        (el.nodeName === "A" && name === "href") ||
        (/^T[DH]$/.test(el.nodeName) && /^(colspan|rowspan)$/.test(name));
      if (!keep) el.removeAttribute(name);
    }
  }

  let md = escapeMdx(turndown.turndown(body.innerHTML))
    .replace(/ /g, " ")
    .replace(/[ \t]+$/gm, "")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
  if (/\\<(table|div|p|span|figure)\b/i.test(md)) report.problems.push("raw HTML left unconverted");
  md = md.replace(/@@BLOCK(\d+)@@/g, (_m, i) => blocks[Number(i)]);
  return { md, report };
}

