/** Rank Math's <title> and meta description as served, so the SERP snippet is unchanged. */
async function servedMeta(slug) {
  const doc = domino.createDocument(await (await fetchOk(`${HOST}/${slug}/`)).text());
  const get = (sel, a) => doc.querySelector(sel)?.getAttribute(a)?.trim() ?? "";
  return {
    title: doc.querySelector("title")?.textContent.trim() ?? "",
    description: get('meta[name="description"]', "content"),
    ogImage: get('meta[property="og:image"]', "content"),
    ogAlt: get('meta[property="og:image:alt"]', "content"),
  };
}

