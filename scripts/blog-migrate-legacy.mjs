/** Where a link to the old blog should now point. Returns null to leave it. */
function rewriteLegacyHref(href) {
  const lp = legacyPathOf(href);
  if (!lp) return null;
  const segs = lp.path.split("/").filter(Boolean);
  if (segs.length === 0) return "/blog";
  if (segs[0] === "wp-content") return mediaMap[`${HOST}${lp.path}`] ?? null;
  if (segs[0] === "category" && segs[1]) {
    const cat = CATEGORIES[segs[1]];
    return cat ? `/blog/category/${categorySlug(cat)}` : "/blog";
  }
  if (segs.length === 1) {
    const s = RENAMED[segs[0]] ?? segs[0];
    if (MOVED[s]) return MOVED[s] + lp.hash;
    if (migratedSlugs.has(s)) return `/blog/${s}${lp.hash}`;
    if (pageSlugs.has(s)) return doorwayDestination(s);
  }
  return null;
}

