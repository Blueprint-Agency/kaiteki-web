/** A link to the legacy host as { path, hash }, or null. */
function legacyPathOf(href) {
  // One post pasted the URL twice into its href ("…/ellanse/https://…/ellanse/").
  href = (href || "").replace(/^(https?:\/\/[^\s]+?\/)(?=https?:\/\/)/i, "");
  const m = /^(?:https?:)?\/\/(?:www\.)?blog\.kaiteki\.my(\/[^?#]*)?([?#].*)?$/i.exec(href || "");
  return m ? { path: m[1] || "/", hash: (m[2] || "").startsWith("#") ? m[2] : "" } : null;
}

